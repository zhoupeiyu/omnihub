import { readFile, writeFile } from 'node:fs/promises';

// Keep the source snapshot fixed when rebuilding. A changed source needs a new translation.
const readJson = async path => JSON.parse(await readFile(new URL(path, import.meta.url), 'utf8'));
const snapshot = await readJson('../content/repository-description-snapshot.json');
const translations = await readJson('../content/repository-translations.zh.json');
const sources = new Map(snapshot.map(repo => [repo.key.toLowerCase(), repo.description]));
if (sources.size !== snapshot.length) throw new Error('Duplicate repository keys in source snapshot');

const entries = {};
for (const [key, text] of Object.entries(translations)) {
  const source = sources.get(key);
  if (key !== key.toLowerCase() || typeof source !== 'string' || !source.trim()) {
    throw new Error(`Missing translation source for ${key}`);
  }
  if (typeof text !== 'string' || !/\p{Script=Han}/u.test(text)) {
    throw new Error(`Missing Chinese text for ${key}`);
  }
  entries[key] = {source, text};
}

const output = '// Generated by scripts/build-repository-translations.mjs. Edit content/repository-translations.zh.json.\n'
  + `export const REPOSITORY_TRANSLATIONS_ZH = ${JSON.stringify(entries, null, 2)};\n`;
await writeFile(new URL('../public/repository-translations.zh.js', import.meta.url), output);
console.log(`Built ${Object.keys(entries).length} Chinese repository introductions; source data unchanged.`);
