import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync,rmSync} from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import http from 'node:http';

test('owner-only corrections preserve sources, override imports and respect public evidence boundaries', async t => {
  const directory = mkdtempSync(path.join(os.tmpdir(),'omnihub-curation-test-'));
  process.env.OMNIHUB_DATA_DIR = directory;
  const {db} = await import('../lib/db.js');
  const {handleApi} = await import('../lib/api.js');
  const {createLibraryCuration} = await import('../lib/library-curation.js');
  const store = createLibraryCuration(db);
  for (const [id,name] of [[1,'zane'],[2,'alice'],[3,'Zane']]) db.prepare('INSERT INTO users(id,username,password_hash,salt) VALUES(?,?,?,?)').run(id,name,'fixture','fixture');
  for (const [token,user] of [['test-owner-session',1],['test-reader-session',2],['test-lookalike-session',3]]) db.prepare('INSERT INTO sessions(token,user_id) VALUES(?,?)').run(token,user);
  const insert = db.prepare("INSERT INTO inbox(id,user_id,source,external_id,title,url,content,visibility,media) VALUES(?,?,'x',?,?,?,?,?,?)");
  for (const [id,user,visibility] of [[1,1,'public'],[2,1,'private'],[3,2,'public'],[4,1,'public']]) insert.run(id,user,String(id),'教程 '+id,`https://x.com/example/status/${id}`,'原始收藏 '+id,visibility,'[]');
  db.prepare("INSERT INTO prompts(user_id,title,text,category,source_inbox_id) VALUES(1,'教程','原始收藏 1','研究',1)").run();
  db.prepare("INSERT INTO repository_assets(user_id,repo_key,owner,name,repository_url) VALUES(1,'example/repo','example','repo','https://github.com/example/repo')").run();
  db.prepare("INSERT INTO repository_sources(repository_id,inbox_id,external_id) VALUES(1,1,'1')").run();
  const originals = JSON.stringify(db.prepare('SELECT * FROM inbox ORDER BY id').all());
  const server = http.createServer(async (req,res) => { if (!await handleApi(req,res,new URL(req.url,'http://localhost').pathname)) {res.writeHead(404);res.end();} });
  await new Promise(resolve => server.listen(0,'127.0.0.1',resolve));
  t.after(async () => {await new Promise(resolve => server.close(resolve)); db.close(); rmSync(directory,{recursive:true,force:true});});
  const base = `http://127.0.0.1:${server.address().port}`;
  const request = (route,{token,body,method,origin,...headers}={}) => fetch(base+route,{method:method || (body ? 'PUT' : 'GET'),
    headers:{...(token ? {cookie:`omnihub_session=${token}`} : {}),...(body ? {'content-type':'application/json'} : {}),...(origin ? {origin} : {}),...headers},body:body ? JSON.stringify(body) : undefined});
  const endpoint = '/api/library-classification/source/1';
  const data = {type:'method',title:'先研究，再实现',summary:'把原帖中的方法与指令分开。',body:'## 步骤\n\n先研究，再实现。',promptText:'请先研究可用方案。',promptCategory:'研究',tags:['工作流'],relatedSourceIds:[]};
  for (const method of ['GET','PUT']) {
    assert.equal((await request(endpoint,{method,body:method === 'PUT' ? {revision:0,data} : undefined})).status,401);
    for (const token of ['test-reader-session','test-lookalike-session']) assert.equal((await request(endpoint,{method,token,body:method === 'PUT' ? {revision:0,data} : undefined})).status,404);
  }
  const owner = {token:'test-owner-session'};
  assert.equal((await request('/api/library-classification/source/3',owner)).status,404);
  assert.equal((await request('/api/library-classification/source/3',{...owner,body:{revision:0,data}})).status,404);
  assert.equal((await request(endpoint,{...owner,origin:'https://evil.example',body:{revision:0,data}})).status,403);
  assert.equal((await request(endpoint,{...owner,'sec-fetch-site':'cross-site',body:{revision:0,data}})).status,403);
  assert.equal((await request(endpoint,{...owner,'content-type':'text/plain',body:{revision:0,data}})).status,415);
  assert.equal((await request(endpoint,{...owner,body:{revision:0,data,userId:2}})).status,400);
  assert.equal((await request(endpoint,{...owner,body:{revision:0,data:{...data,type:'unknown'}}})).status,400);
  assert.equal((await request(endpoint,{...owner,body:{revision:0,data:{...data,body:''}}})).status,400);
  assert.equal((await request(endpoint,{...owner,body:{revision:0,data:{...data,relatedSourceIds:[3]}}})).status,404);
  const saved = await request(endpoint,{...owner,origin:base,body:{revision:0,data}});
  assert.equal(saved.status,200,await saved.text());
  assert.equal((await request(endpoint,{...owner,body:{revision:0,data}})).status,409);
  assert.throws(() => store.write(1,'source','1',1,data,'reviewed'),e => e.status === 409);
  assert.equal(JSON.stringify(db.prepare('SELECT * FROM inbox ORDER BY id').all()),originals);
  const history = db.prepare('SELECT * FROM library_curation_history').all();
  assert.equal(history.length,1);
  assert.equal(history[0].actor_id,1);
  assert.equal(JSON.parse(history[0].before_data).type,'prompt');
  assert.equal(JSON.parse(history[0].after_data).type,'method');
  const readJson = async route => (await request(route)).json();
  assert.equal((await readJson('/api/prompt-library'))[0].text,data.promptText);
  assert.equal((await readJson('/api/knowledge-library'))[0].type,'method');
  const method = await readJson('/api/knowledge-library/method-1');
  assert.equal(method.sources[0].url,'https://x.com/example/status/1');
  assert.equal(method.body,data.body);
  db.prepare("UPDATE prompts SET text='自动导入覆盖了旧正文'").run();
  assert.equal((await readJson('/api/prompt-library'))[0].text,data.promptText);
  assert.equal((await request(endpoint,{...owner,body:{revision:1,data:{...data,promptText:''}}})).status,200);
  assert.equal((await readJson('/api/prompt-library')).length,0);
  assert.equal((await request(endpoint,{...owner,body:{revision:2,data:{...data,relatedSourceIds:[2]}}})).status,200);
  assert.equal((await readJson('/api/knowledge-library')).length,0);
  assert.equal((await request('/api/knowledge-library/method-1')).status,404);
  assert.equal((await readJson('/api/prompt-library')).length,0);
  assert.equal((await (await request('/api/knowledge-library',owner)).json()).length,1);
  assert.equal((await request(endpoint,{...owner,body:{revision:3,data:{...data,type:'source'}}})).status,200);
  assert.equal((await readJson('/api/knowledge-library')).length,0);
  assert.equal((await readJson('/api/prompt-library')).length,0);
  assert.equal((await request(endpoint,{...owner,body:{revision:4,data:{...data,type:'prompt'}}})).status,200);
  assert.equal((await readJson('/api/prompt-library')).length,1);
  db.prepare("UPDATE inbox SET visibility='private' WHERE id=1").run();
  assert.equal((await readJson('/api/prompt-library')).length,0);
  db.prepare("UPDATE inbox SET visibility='public',status='ignored' WHERE id=1").run();
  assert.equal((await readJson('/api/prompt-library')).length,0);
  db.prepare("UPDATE inbox SET status='pending' WHERE id=1").run();
  const repoRoute = '/api/library-classification/repository/example/repo';
  const repoData = {uses:['agent.coding'],forms:['skill']};
  assert.equal((await request(repoRoute,{body:{revision:0,data:repoData}})).status,401);
  assert.equal((await request(repoRoute,{token:'test-reader-session',body:{revision:0,data:repoData}})).status,404);
  assert.equal((await request(repoRoute,{...owner,body:{revision:0,data:{uses:['fake'],forms:['skill']}}})).status,400);
  assert.equal((await request(repoRoute,{...owner,body:{revision:0,data:repoData}})).status,200);
  db.prepare("UPDATE repository_assets SET metadata='{}'").run();
  assert.deepEqual((await readJson('/api/repositories'))[0].metadata.classification.uses,repoData.uses);
  assert.deepEqual((await readJson('/api/repositories/example/repo')).metadata.classification.forms,repoData.forms);
  assert.equal((await request(repoRoute,{...owner,body:{revision:0,data:repoData}})).status,409);
  // Long-term rules stay copyable in method details, not as task-prompt cards.
  const rules = {...data,title:'Agent 长期规则',promptText:'始终先检查事实和前提。',promptCategory:'Agent 系统'};
  assert.equal((await request(endpoint,{...owner,body:{revision:5,data:{...rules,type:'prompt'}}})).status,400);
  assert.equal((await request(endpoint,{...owner,body:{revision:5,data:rules}})).status,200);
  assert.equal((await readJson('/api/prompt-library')).length,0);
  const ruleDetail = await readJson('/api/knowledge-library/method-1');
  assert.equal(ruleDetail.promptText,rules.promptText);
  assert.equal(ruleDetail.hasPrompt,false);
  // Future automatic system-rule imports must not leak back into the task library.
  db.prepare("INSERT INTO prompts(user_id,title,text,category,kind,source_inbox_id) VALUES(1,'系统规则','长期约束','Agent 系统','agent_system',4)").run();
  assert.equal((await readJson('/api/prompt-library')).length,0);
  assert.equal((await request('/api/library-classification/source/4',{...owner,body:{revision:0,data:{...data,type:'prompt'}}})).status,200);
  const taskPrompts = await readJson('/api/prompt-library');
  assert.equal(taskPrompts.length,1);
  assert.equal(taskPrompts[0].category,'研究');
  assert.equal(taskPrompts[0].kind,'research');
  assert.equal(JSON.stringify(db.prepare('SELECT * FROM inbox ORDER BY id').all()),originals);
});
